"""Embed locally supplied, board-matched CYW43455 firmware for an opt-in build.

Input files and their redistribution licenses remain the caller's responsibility.
No firmware or network credentials are downloaded or supplied by this tool.
"""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('firmware', 'nvram', 'clm', 'country', 'output'):
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--regrev', type=int, required=True)
    args = parser.parse_args()
    if len(args.country) != 2 or any(c < 'A' or c > 'Z' for c in args.country) or not -1 <= args.regrev <= 2147483647:
        parser.error('Use an explicit two-letter country and a signed regulatory revision >= -1.')
    blobs = {name: Path(getattr(args, name)).read_bytes() for name in ('firmware', 'nvram', 'clm')}
    for name, limit in (('firmware', 1048576), ('nvram', 16384), ('clm', 262144)):
        if not blobs[name] or len(blobs[name]) > limit:
            parser.error(f'{name} is empty or exceeds {limit} bytes')
    if len(blobs['firmware']) < 4 or blobs['firmware'][:4] == b'\0\0\0\0':
        parser.error('Firmware must contain a nonzero reset vector.')
    try:
        blobs['nvram'].decode('ascii')
    except UnicodeDecodeError:
        parser.error('NVRAM must be the board-matched ASCII text file.')
    if b'\0' in blobs['nvram']:
        parser.error('NVRAM input is text, not an already-packed binary.')
    output = Path(args.output).resolve()
    if output.suffix.lower() != '.c':
        parser.error('Output must be a C source file with a .c extension.')
    if output in [Path(getattr(args, name)).resolve() for name in blobs]:
        parser.error('Output must not overwrite an input file.')
    marker = '/* Firmware data generated by tools/embed_wifi.py. */'
    if output.exists() and not output.read_text(encoding='utf-8').startswith(marker):
        parser.error('Refusing to overwrite an existing file that was not generated by this tool.')
    manifest_path = output.with_suffix('.json')
    if manifest_path in [Path(getattr(args, name)).resolve() for name in blobs]:
        parser.error('Manifest must not overwrite an input file.')
    if manifest_path.exists():
        try:
            previous = json.loads(manifest_path.read_text(encoding='utf-8'))
        except (ValueError, UnicodeError):
            parser.error('Refusing to overwrite an unrelated manifest file.')
        if not isinstance(previous, dict) or previous.get('format') != 'vantage-wifi-assets-v1':
            parser.error('Refusing to overwrite an unrelated manifest file.')
    lines = [marker, '#include <vantage/drivers/wifi.h>', '']
    for name, data in blobs.items():
        lines.append(f'static const unsigned char {name}[] = {{')
        for offset in range(0, len(data), 16):
            lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[offset:offset + 16]) + ',')
        lines.extend(['};', ''])
    lines += ['const WifiFirmware* pi4_wifi_firmware(void) {', '    static const WifiFirmware assets = {',
              '        firmware, sizeof(firmware), nvram, sizeof(nvram), clm, sizeof(clm),',
              f'        "{args.country}", {args.regrev}', '    };', '    return &assets;', '}', '']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    manifest = {name: {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()} for name, data in blobs.items()}
    manifest.update(format='vantage-wifi-assets-v1', country=args.country, regulatory_revision=args.regrev)
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {output}. Retain the firmware/NVRAM/CLM redistribution licenses with any distributed image.')


if __name__ == '__main__': main()
